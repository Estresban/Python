'''Ejercicio 2. Área y perímetro
Solicita la base y la altura de un rectángulo.

Calcula y muestra:

Área.
Perímetro.'''

ancho = int(input("Ingrese el valor del ancho: "))
altura = int(input("Ingrese el valor del altura: "))
print ("El area del rectangulo es: ", (ancho * altura))
print ("El perimetro del rectangulo es: ", 2 * (ancho + altura))